#!/usr/bin/env -S nix develop -c node
// @ts-check
/**
 * Render the workspaces slice 2 mockup: the real Darkroom chrome in the gallery,
 * with the workspace-rows fixtures. Run from the caliper checkout root, so
 * `nix develop` provides CHROMIUM.
 *
 *   docs/design/mockups/workspaces-rows/shoot.mjs   # out/*.png and index.html
 *
 * The live mockup is the gallery itself: `nix develop -c node scripts/ui/serve.mjs`,
 * then `?fixture=workspaceRowChecked` (or workspaceRowNew, workspaceRowWriting,
 * workspaceRowChecking, workspaceRowBoard). The size ladder and the reachability
 * of every control are gated by `scripts/ui/verify.mjs`.
 */
import { chromium } from "playwright-core"
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { SIZES, serveGallery } from "../../../../scripts/ui/lib.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, "out")
mkdirSync(out, { recursive: true })
const LADDER = [
  { name: "generous", width: 1920, height: 1200, scale: 1 }, { name: "medium", width: 960, height: 1000, scale: 1 },
  { name: "narrow-tall", width: 390, height: 900, scale: 2 }, { name: "wide-short", width: 1280, height: 300, scale: 1 },
  { name: "tiny", width: 240, height: 180, scale: 3 },
]
const STATES = [
  { fixture: "workspaceRowNew", name: "new", caption: "New row: the bar says what the row must show and check" },
  { fixture: "workspaceRowWriting", name: "writing", caption: "The row agent writes the row; its record shows the log" },
  { fixture: "workspaceRowChecking", name: "checking", caption: "Today is checked; idea 5 is checking; 6 and 7 wait" },
  { fixture: "workspaceRowChecked", name: "checked", caption: "Every column checked; the record shows why Today fails" },
  { fixture: "workspaceRowBoard", name: "board", caption: "The checked board, side panel closed" },
]
/** @type {{ file: string, caption: string, fixture: string, size: { width: number, height: number, scale: number }, scheme: "dark" | "light" }[]} */
const shots = []
for (const state of STATES) for (const size of SIZES) shots.push({ file: `${state.name}-${size.name}-dark.png`, caption: `${state.caption}, ${size.name}`, fixture: state.fixture, size, scheme: "dark" })
for (const size of SIZES) shots.push({ file: `checked-${size.name}-light.png`, caption: `Every column checked, ${size.name}, light`, fixture: "workspaceRowChecked", size, scheme: "light" })
for (const size of LADDER) shots.push({ file: `ladder-${size.name}.png`, caption: `The checked board at ${size.name} (${size.width} × ${size.height})`, fixture: "workspaceRowBoard", size, scheme: "dark" })

const gallery = await serveGallery()
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM })
/** @type {string[]} */
const errors = []
try {
  for (const shot of shots) {
    const context = await browser.newContext({ viewport: { width: shot.size.width, height: shot.size.height }, deviceScaleFactor: shot.size.scale, colorScheme: shot.scheme })
    const page = await context.newPage()
    page.on("pageerror", error => errors.push(`${shot.file}: ${error.message}`))
    await page.goto(`${gallery.origin}/?fixture=${shot.fixture}`)
    await page.waitForSelector('[data-cal="chrome"]')
    await page.evaluate(() => document.fonts.ready)
    // The new row is the last one, under the fold of a stacked board: scroll to it, as a person would.
    // The column names stay, because they stick to the top.
    await page.evaluate(() => { const body = document.querySelector(".ws-board__body"); if (body) body.scrollTop = body.scrollHeight })
    await page.waitForTimeout(300)
    await page.screenshot({ path: join(out, shot.file) })
    console.log(shot.file)
    await context.close()
  }
} finally {
  await browser.close()
  await gallery.close()
}
const figures = shots.map(shot => `<figure><a href="out/${shot.file}"><img src="out/${shot.file}" alt="${shot.caption}" loading="lazy"></a><figcaption>${shot.caption}</figcaption></figure>`).join("\n")
writeFileSync(join(here, "index.html"), `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Workspaces, slice 2</title><link rel="icon" href="data:,">
<style>body{margin:0;padding:1.5rem;background:#121316;color:#ECECEE;font:14px/1.5 system-ui,sans-serif}h1{font-size:18px;margin:0 0 .3rem}p{color:#A3A6AE;margin:0 0 1.2rem;max-width:60rem}
main{display:grid;grid-template-columns:repeat(auto-fill,minmax(min(100%,28rem),1fr));gap:1.4rem}figure{margin:0}img{width:100%;height:auto;display:block;border:1px solid #303237;border-radius:6px}figcaption{color:#A3A6AE;font-size:12px;margin-top:.35rem}</style></head>
<body><h1>Workspaces, slice 2: scratch rows that check</h1><p>Generated by shoot.mjs from the real chrome. Every Pico screen and every check result is real. See README.md for what is staged.</p><main>
${figures}
</main></body></html>
`)
if (errors.length) { console.error(errors.join("\n")); process.exitCode = 1 }
console.log(`\n${shots.length} images in ${out}`)
